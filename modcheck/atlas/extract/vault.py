    # -- 90 coverage ----------------------------------------------------------------------
    def coverage(self) -> None:
        hooked = self.hooked_types()
        sc = self.surface["counts"]
        pk = self.surface["packages"]
        depth4 = sorted({".".join(p.split(".")[:4]) for p in pk})
        hooked_pkgs = {pkg_of(t) for t in hooked}
        modules = self.fabric["modules"]
        api_with_members = sum(len(m["api"]) for m in modules)
        rb = self.edges["resolution_by_relation"]
        b = fm(type="coverage", generated_at=self.edges["generated_at"]) + "# Coverage, with denominators\n\n"
        b += ("Seven separate measures. None of them is 'supported'. A capability record, a linked "
              "note, or a passing schema establishes nothing about behaviour.\n\n")
        b += "## 1. Surface inventory\n\n"
        b += f"- artifacts classified: {len(self.corpus['artifacts'])} / {len(self.corpus['artifacts'])} (0 unclassified); groups {json.dumps(self.corpus['groups'])}\n"
        b += (f"- classes in the processed compile jar: {sc['classes']} ({sc['top_level']} top-level) in {sc['packages']} packages, "
              f"{sc['members']} declared members -- all inventoried (`extracted:minecraft_surface.json.gz`)\n")
        b += f"- depth-4 packages: {len(depth4)}; with at least one Fabric API hook: {len(hooked_pkgs)}\n"
        b += f"- data pack entry types inventoried: {len(self.corpus['minecraft']['data_entries_by_type'])} (from the jar)\n"
        b += f"- Fabric API modules inventoried: {len(modules)} / {self.corpus['groups'].get('fabric_api_module')}\n"
        env = self.env
        b += (f"- resolved environment recorded: compile {env['counts'].get('compileClasspath')}, runtime {env['counts'].get('runtimeClasspath')}, "
              f"test {env['counts'].get('testRuntimeClasspath')} entries, all hashed; processed-vs-cache jar diff: "
              f"{env['minecraft_jar_processing']['classes_with_different_bytes']} classes\n\n")
        b += "## 2. Extraction\n\n"
        n_declared = sum(m["counts"]["mixin_classes_declared"] for m in modules)
        n_found = sum(m["counts"]["mixin_classes_found"] for m in modules)
        n_fail = sum(m["counts"]["extraction_failures"] for m in modules)
        inj_kinds = collections.Counter(e["injector"] for e in self.injection_edges())
        b += f"- mixin classes: {n_found} found by annotation / {n_declared} declared in configs; extraction failures: {n_fail}\n"
        b += f"- injections: {sum(inj_kinds.values())} by injector {json.dumps(dict(inj_kinds.most_common()))}\n"
        b += f"- Fabric API classes with public surface extracted: {api_with_members} / {sum(m['counts']['api_classes'] for m in modules)}\n"
        b += f"- vanilla types that are hook targets: {len(hooked)}; every one has its declared members in the surface\n\n"
        b += "## 3. Workflow information\n\n"
        areas = collections.Counter(w["area"] for w in self.workflows)
        b += f"- workflow families authored: {len(self.workflows)} across {len(areas)} / 8 areas: {dict(areas)}\n"
        b += f"- families with interaction analysis: {sum(1 for w in self.workflows if w['status']['interaction_analysed'])} / {len(self.workflows)}\n\n"
        b += "## 4. Interaction contracts\n\n"
        b += f"- typed edges: {len(self.edges['edges'])} -- by relation {json.dumps(self.edges['counts'])}\n"
        b += f"- by evidence class: {json.dumps(self.edges['evidence_classes'])}\n"
        b += f"- resolution of injection selectors: injects_into {json.dumps(rb.get('injects_into'))}; wraps {json.dumps(rb.get('wraps'))}; replaces {json.dumps(rb.get('replaces'))}\n"
        b += f"- resolution of injection points (@At): {json.dumps(self.edges['injection_point_resolution'])}\n"
        b += f"- resolution of calls / reads / writes: {json.dumps(rb.get('calls'))} / {json.dumps(rb.get('reads'))} / {json.dumps(rb.get('writes'))}\n"
        b += f"- events with an identified publisher: {sum(1 for v in self.events().values() if v['publishers'])} / {len(self.events())}\n"
        b += f"- events with an analyst-stated subscriber contract: {sum(1 for c in self.contracts if c['kind'] == 'event')} / {len(self.events())}\n"
        b += f"- shared targets (potential interactions, no verdict): {len(self.edges['shared_targets'])}; same-point overlap: not computed\n"
        b += f"- curated interaction records in the store: {len(self.pack.records('interaction'))}\n\n"
        b += "## 5. Executable analysis (ModCheck)\n\n"
        b += f"- capability records: {len(self.pack.records('capability'))}; failures with a detector: {sum(1 for r in self.pack.records('failure') if (r.get('detector') or {}).get('detectable') == 'yes')} / {len(self.pack.records('failure'))}\n"
        b += ("- static mixin-collision analysis over arbitrary mod jars: NOT implemented (the extractor and resolver exist "
              "under atlas/extract; the jvm inspector does not call them; the required order is index -> exact resolution -> applicability -> composition rule)\n\n")
        b += "## 6. Runtime and transformation evidence\n\n"
        b += "- observed edges: 0. No game has run.\n"
        if self.transform:
            n = len(self.transform["scenarios"])
            ok = sum(1 for s in self.transform["scenarios"] if s["transformed"])
            b += (f"- executed_transformation: {n} scenarios run through the pinned Mixin transformer ({ok} transformed, "
                  f"{n - ok} refused at transformation); transformer evidence, not Minecraft evidence\n\n")
        b += "## 7. Creation / maintenance automation\n\n"
        b += "- deterministic generators: 6 mechanisms (Fabric only); the reference lantern was hand-authored, not generated\n- agent execution: boundary exists, unavailable here\n\n"
        # per-system state
        contract_pkgs: collections.Counter = collections.Counter()
        hs = self.handler_sites()
        for c in self.contracts:
            if not c["id"].startswith("event:"):
                continue
            for p in self.events().get(c["id"][6:], {}).get("publishers", []):
                for e in hs.get((p["from"].get("owner"), p["from"]["id"]), []):
                    contract_pkgs[pkg_of(e["to"]["owner"])] += 1
        system_notes = {s["id"] for s in self.systems}
        req_pkgs: dict[str, list[str]] = collections.defaultdict(list)
        for r in self.requests:
            for a in r["affected_systems"]:
                for pkg in depth4:
                    if a.startswith(pkg + " ") or a.startswith(pkg + "."):
                        req_pkgs[pkg].append(r["id"] + ("" if r["status"]["implemented"] == "none" else " (implemented, hand-authored)"))
        b += ("## Per-system state\n\nColumns are independent: *inventoried* = every class and member of the package is in the surface; "
              "*inspected* = hooked types with their edges resolved; *contract-mapped* = analyst contracts whose publication site is in the package; "
              "*analysed* = an analyst system note exists; *in ModCheck* = a request analysis names it; *validated* = the validation scope of that implementation.\n\n"
              "| package | inventoried | inspected | contract-mapped | analysed | in ModCheck | validated |\n|---|---|---|---|---|---|---|\n")
        for pkg in sorted(set(depth4) | system_notes):
            n_types = sum(1 for t in hooked if pkg_of(t) == pkg)
            inspected = f"{n_types} hooked types, edges resolved" if n_types else "no hooks"
            cm = f"{contract_pkgs[pkg]} contracts" if contract_pkgs.get(pkg) else "no"
            an = "system note" if pkg in system_notes else ("edges only" if n_types else "no")
            reqs = req_pkgs.get(pkg, [])
            inm = "; ".join(reqs) if reqs else "no"
            val = "JUnit with fakes, gradle build; no game run" if any("implemented" in r for r in reqs) else "none"
            b += f"| `{pkg}` | all classes | {inspected} | {cm} | {an} | {inm} | {val} |\n"
        self.put("90-Coverage/_index.md", self._render_ref(b))

