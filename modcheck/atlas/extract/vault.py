"""Generate the Obsidian-compatible vault from records and extracted facts.

Everything under ``atlas/vault/`` is generated by this file: delete the directory
and this rebuilds it. Notes carry stable ids in their filenames and link back to
the record or extracted entry they came from. Authored analyst material lives in
``atlas/authored/`` and is rendered under ``_authored/`` with a visible banner; a
generated note may LINK to an authored one, never absorb it.

Evidence labels are rendered exactly as recorded. Nothing here promotes a
static_inference to a direct_reference, an executed_transformation to an
observation, or a documented claim to an observed one.
"""
from __future__ import annotations

import collections
import gzip
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parents[0] / "src"))
from modcheck import yamlio  # noqa: E402
from modcheck.store import Store  # noqa: E402

EXTRACTED = ROOT / "extracted"
VAULT = ROOT / "vault"
AUTHORED = ROOT / "authored"
# A typed reference: dot-separated segments, never ending in a dot. Shared with validate.py.
REF_PATTERN = r"\b(mechanism|question|workflow|event|type|source|extracted|record|request|scenario):([A-Za-z0-9_/#$-]+(?:\.[A-Za-z0-9_/#$-]+)*)"

GENERATED = ("> [!info] Generated\n> Built by `atlas/extract/vault.py` from the records and "
             "extracted facts it links to. Do not edit; edit the source and regenerate.\n\n")
AUTHORED_BANNER = ("> [!warning] Analyst-authored\n> Interpretation, not extraction. Claims "
                   "cite evidence ids; anything uncited is opinion. Reviewed corrections go "
                   "into the store records or the extractors, never into a generated note.\n\n")
ACC = {0x0001: "public", 0x0002: "private", 0x0004: "protected", 0x0008: "static", 0x0010: "final",
       0x0400: "abstract", 0x0100: "native", 0x1000: "synthetic"}


def slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", text).strip("_")[:120]


def link(target: str, label: str | None = None) -> str:
    return f"[[{target}|{label}]]" if label else f"[[{target}]]"


def write(path: Path, body: str, generated: bool = True) -> None:
    """Write a note: frontmatter first (Obsidian requires it at byte 0), then the banner."""
    path.parent.mkdir(parents=True, exist_ok=True)
    banner = GENERATED if generated else AUTHORED_BANNER
    if body.startswith("---\n") and "\n---\n" in body[4:]:
        head, _, rest = body[4:].partition("\n---\n")
        body = "---\n" + head + "\n---\n\n" + banner + rest.lstrip("\n")
    else:
        body = banner + body
    path.write_text(body)


def fm(**fields) -> str:
    lines = ["---"]
    for k, v in fields.items():
        if isinstance(v, (list, tuple)):
            lines.append(f"{k}:")
            lines += [f"  - {json.dumps(x)}" for x in v]
        else:
            lines.append(f"{k}: {json.dumps(v)}")
    lines.append("---")
    return "\n".join(lines) + "\n\n"


def pkg_of(internal_or_dotted: str) -> str:
    """Depth-4 package of a class (`net.minecraft.world.level` for `net/minecraft/world/level/Level$1`)."""
    dotted = internal_or_dotted.replace("/", ".")
    return ".".join(dotted.split(".")[:-1][:4])


def full_pkg(internal: str) -> str:
    return internal.rsplit("/", 1)[0].replace("/", ".") if "/" in internal else "(default)"


def access_words(access: int) -> str:
    return " ".join(w for bit, w in ACC.items() if access & bit)


def short(dotted: str) -> str:
    return dotted.replace("/", ".").split(".")[-1]


# ---------------------------------------------------------------------------
class Atlas:
    def __init__(self) -> None:
        self.corpus = json.loads((EXTRACTED / "corpus.json").read_text())
        self.fabric = json.loads((EXTRACTED / "fabric_api.json").read_text())
        self.registries = json.loads((EXTRACTED / "minecraft_registries.json").read_text())
        self.edges = json.loads((EXTRACTED / "edges.json").read_text())
        self.env = json.loads((EXTRACTED / "resolved_environment.json").read_text())
        with gzip.open(EXTRACTED / "minecraft_surface.json.gz", "rt") as fh:
            self.surface = json.load(fh)
        tpath = EXTRACTED / "mixin_transformation_tests.json"
        self.transform = json.loads(tpath.read_text()) if tpath.exists() else None
        self.store = Store()
        self.pack = self.store.pack("minecraft")
        self.workflows = self._load_authored("workflows")
        self.questions = self._load_authored("questions")
        self.systems = self._load_authored("systems")
        self.requests = self._load_authored("requests")
        self.contracts = self._load_authored("contracts")
        self.written: list[Path] = []
        self.note_index: set[str] = set()

    def _load_authored(self, kind: str) -> list[dict]:
        out = []
        for path in sorted((AUTHORED / kind).glob("*.yaml")):
            data = yamlio.load_path(path)
            for entry in (data if isinstance(data, list) else [data]):
                entry["_path"] = str(path.relative_to(ROOT))
                out.append(entry)
        return out

    def put(self, rel: str, body: str, generated: bool = True) -> str:
        path = VAULT / rel
        write(path, body, generated)
        self.written.append(path)
        self.note_index.add(rel[:-3] if rel.endswith(".md") else rel)
        return rel[:-3] if rel.endswith(".md") else rel

    # -- indexes ------------------------------------------------------------
    def hooked_types(self) -> dict[str, list[dict]]:
        """vanilla internal name -> edges whose `to` endpoint lives in that type (injections, calls, reads, writes)."""
        idx: dict[str, list[dict]] = collections.defaultdict(list)
        for e in self.edges["edges"]:
            to = e["to"]
            if to["kind"] in ("registry", "event"):
                continue
            owner = to.get("owner") or (to["id"] if to["kind"] == "type" else None)
            if owner and owner.replace(".", "/").startswith(("net/minecraft/", "com/mojang/")):
                idx[owner.replace(".", "/")].append(e)
        return idx

    def events(self) -> dict[str, dict]:
        ev: dict[str, dict] = {}
        for e in self.edges["edges"]:
            if e["relation"] == "callback_of":
                ev.setdefault(e["to"]["id"], {"callback": None, "publishers": [], "module": e.get("module")})
                ev[e["to"]["id"]]["callback"] = e["from"]["id"]
            elif e["relation"] == "publishes_event":
                ev.setdefault(e["to"]["id"], {"callback": None, "publishers": [], "module": e.get("module")})
                ev[e["to"]["id"]]["publishers"].append(e)
        return ev

    def injection_edges(self) -> list[dict]:
        return [e for e in self.edges["edges"] if e["relation"] in ("injects_into", "wraps", "replaces")]

    def handler_sites(self) -> dict[tuple, list[dict]]:
        """(handler owner, handler name) -> injection edges of that handler."""
        idx: dict[tuple, list[dict]] = collections.defaultdict(list)
        for e in self.injection_edges():
            idx[(e["from"].get("owner"), e["from"]["id"])].append(e)
        return idx

    def type_link(self, internal_or_dotted: str, label: str | None = None) -> str:
        dotted = internal_or_dotted.replace("/", ".")
        rel = f"40-Interfaces/{slug(dotted)}"
        if rel in self.note_index:
            return link(rel, label or short(dotted))
        return f"`{label or dotted}`"

    # -- generation ---------------------------------------------------------
    def build(self) -> None:
        for child in VAULT.iterdir() if VAULT.exists() else []:
            shutil.rmtree(child) if child.is_dir() else child.unlink()
        self.interfaces()          # first: other notes link to interface notes only if they exist
        self.scope()
        self.systems_notes()
        self.mechanisms()
        self.interactions()
        self.failures()
        self.workflow_notes()
        self.request_notes()
        self.question_notes()
        self.coverage()
        self.index()

    # -- 00 scope -------------------------------------------------------------
    def scope(self) -> None:
        c = self.corpus
        mc = c["minecraft"]
        v = mc["version_json"]
        env = self.env
        on_rt = {e["path"] for e in env["configurations"].get("runtimeClasspath", [])}
        on_cp = {e["path"] for e in env["configurations"].get("compileClasspath", [])}
        rows = ["| group | artifact | version | classes (top/nested) | compile | runtime | sha256 |", "|---|---|---|---|---|---|---|"]
        for a in sorted(c["artifacts"], key=lambda a: (a["group"], a["name"])):
            rows.append(f"| {a['group']} | {a['name']} | {a['version']} | {a['classes_top_level']}/{a['classes_nested']} | "
                        f"{'yes' if a['path'] in on_cp else ''} | {'yes' if a['path'] in on_rt else ''} | `{a['sha256'][:16]}` |")
        body = fm(type="scope", generated_at=c["generated_at"]) + "# Corpus: what was actually resolved\n\n"
        body += ("This is the concrete input set. Every fact in the atlas that is marked "
                 "`direct_reference` or `static_inference` was read from one of these files, "
                 "identified by hash. Anything not listed here is outside the corpus, and the "
                 f"atlas says so in {link('00-Scope/Branches', 'Branches')}.\n\n")
        body += f"**Source of truth:** {c['source_of_truth']}\n\n"
        body += ("## Minecraft Java Edition 26.3 -- pinned identity\n\n"
                 f"- version id `{v['id']}`, world version {v['world_version']}, protocol {v['protocol_version']}\n"
                 f"- Java {v['java_version']}\n"
                 f"- resource pack format {v['pack_version']['resource_major']}.{v['pack_version']['resource_minor']}, "
                 f"data pack format {v['pack_version']['data_major']}.{v['pack_version']['data_minor']}\n"
                 f"- stable: {v['stable']}\n\n")
        proc = env["minecraft_jar_processing"]
        body += ("## Cache inventory versus the resolved environment\n\n"
                 "Two different things, kept apart. The **cache inventory** is every jar in the Gradle caches "
                 "that this project's tooling downloaded. The **resolved environment** is what the reference "
                 f"project's own Gradle build put on its classpaths (`extracted:resolved_environment.json`, "
                 f"{env['method']}).\n\n"
                 f"| configuration | entries |\n|---|---|\n" + "\n".join(f"| {k} | {n} |" for k, n in env["counts"].items()) + "\n\n"
                 f"- corpus artifacts on the runtime classpath: {env['corpus_artifacts_on_runtime_classpath']} / {env['corpus_artifacts_total']}\n"
                 f"- runtime entries outside the corpus: {env['runtime_entries_not_in_corpus']}\n\n"
                 "### The jar a mod compiles against is not Mojang's jar\n\n"
                 f"The compile classpath carries a Loom-processed jar (`{Path(proc['processed_jar']['path']).name}`, "
                 f"sha256 `{proc['processed_jar']['sha256'][:16]}`), not the merged cache jar (`{Path(proc['cache_jar']['path']).name}`, "
                 f"`{proc['cache_jar']['sha256'][:16]}`). Same {proc['entries_processed']} entries; "
                 f"{proc['classes_with_different_bytes']} classes differ: {len(proc['member_access_changes'])} member access "
                 f"changes, {len(proc['class_access_changes'])} class access changes, {len(proc['hierarchy_changes'])} "
                 f"hierarchy changes (interfaces injected). Details: {link('00-Scope/Processed_Jar_Diff')}. Every member "
                 "resolution in the atlas is against the processed jar, because that is what a mod resolves against; "
                 "which module widened what is question:q.processed_jar_change_provenance.\n\n")
        body += f"## Artifacts ({len(c['artifacts'])})\n\n" + "\n".join(rows) + "\n\n"
        body += "## Groups\n\n" + "\n".join(f"- **{g}**: {n}" for g, n in sorted(c["groups"].items())) + "\n"
        self.put("00-Scope/Corpus.md", self._render_ref(body))

        b = fm(type="scope") + "# Processed jar versus cache jar\n\n"
        b += ("What Loom did to Mojang's merged jar before the reference project compiled against it. "
              "`from`/`to` are JVM access flags.\n\n## Hierarchy changes (interfaces injected)\n\n| class | interfaces added |\n|---|---|\n")
        for h in proc["hierarchy_changes"]:
            b += f"| {self.type_link(h['class'])} | {', '.join('`' + i + '`' for i in h['interfaces_added'])} |\n"
        b += "\n## Class access changes\n\n| class | from | to |\n|---|---|---|\n"
        for h in proc["class_access_changes"]:
            b += f"| {self.type_link(h['class'])} | {access_words(h['from'])} | {access_words(h['to'])} |\n"
        b += f"\n## Member access changes ({len(proc['member_access_changes'])})\n\n| class | member | from | to |\n|---|---|---|---|\n"
        for h in proc["member_access_changes"]:
            b += f"| {self.type_link(h['class'])} | `{h['member']}{h['desc'] if h['desc'].startswith('(') else ''}` | {access_words(h['from'])} | {access_words(h['to'])} |\n"
        self.put("00-Scope/Processed_Jar_Diff.md", b)

        self.put("00-Scope/Branches.md", fm(type="scope") + (Path(AUTHORED / "branches.md").read_text()
                 if (AUTHORED / "branches.md").exists() else "# Branches\n\n(no authored branch inventory yet)\n"), generated=False)

        body = fm(type="scope") + "# Data-driven surface shipped in the 26.3 jar\n\n"
        body += ("Everything under `data/minecraft/<type>/` is a data pack the game ships with "
                 "itself. Each type is a modification mechanism that needs no Java: a data pack "
                 "adding or overriding entries here changes the game. Counts are the vanilla "
                 "entries, read from the jar.\n\n| type | vanilla entries |\n|---|---|\n")
        body += "\n".join(f"| `{t}` | {n} |" for t, n in mc["data_entries_by_type"].items())
        body += "\n\n## Assets (resource pack) shipped in the jar\n\n| type | entries |\n|---|---|\n"
        body += "\n".join(f"| `{t}` | {n} |" for t, n in mc["asset_entries_by_type"].items())
        self.put("00-Scope/Data_Driven_Surface.md", body)

        body = fm(type="scope") + "# Source coverage (minecraft pack)\n\n"
        body += "| id | kind | cached | licence |\n|---|---|---|---|\n"
        for sid, s in sorted(self.pack.sources.items()):
            body += f"| `{sid}` | {s.get('kind')} | {'yes' if s.get('evidence_path') else 'no'} | {s.get('license', '?')} |\n"
        self.put("00-Scope/Sources.md", body)

    # -- 20 systems -------------------------------------------------------------
    def systems_notes(self) -> None:
        hooked = self.hooked_types()
        by_pkg: dict[str, list[str]] = collections.defaultdict(list)
        for t in hooked:
            by_pkg[pkg_of(t)].append(t)
        authored = {s["id"]: s for s in self.systems}
        pk = self.surface["packages"]
        # roll the full-package inventory up to depth 4
        depth4: dict[str, dict] = collections.defaultdict(lambda: {"classes": 0, "top_level": 0, "differs": 0, "subpackages": set()})
        for pkg, n in pk.items():
            d4 = ".".join(pkg.split(".")[:4])
            depth4[d4]["classes"] += n["classes"]
            depth4[d4]["top_level"] += n["top_level"]
            depth4[d4]["differs"] += n["differs"]
            depth4[d4]["subpackages"].add(pkg)
        body = fm(type="index") + "# Game systems (by package)\n\n"
        body += ("The declared inventory of the jar a mod compiles against: every class, hooked or not "
                 f"(`extracted:minecraft_surface.json.gz`: {self.surface['counts']['classes']} classes, "
                 f"{self.surface['counts']['members']} members, {self.surface['counts']['packages']} packages, rolled up "
                 "to depth 4 here). `hooked types` counts classes in the package that at least one Fabric API module "
                 "injects into, wraps, calls, reads or writes; a zero means no shipped module touches it, not that "
                 "it cannot be modified. `processed` counts classes Loom changed before compilation.\n\n"
                 "| package | classes | top-level | processed | hooked types | note |\n|---|---|---|---|---|---|\n")
        for pkg in sorted(set(depth4) | set(authored)):
            d = depth4.get(pkg, {"classes": 0, "top_level": 0, "differs": 0, "subpackages": set()})
            n_h = len(by_pkg.get(pkg, []))
            note = link(f"20-Systems/{slug(pkg)}", "note")
            body += f"| `{pkg}` | {d['classes']} | {d['top_level']} | {d['differs']} | {n_h} | {note} |\n"
        self.put("20-Systems/_index.md", self._render_ref(body))

        for sysrec in self.systems:
            b = fm(type="system_note", id=sysrec["id"], side=sysrec["side"]) + f"# {sysrec['title']}\n\n"
            b += f"Package `{sysrec['id']}` -- generated view: {link('20-Systems/' + slug(sysrec['id']), 'inventory and hooked types')}\n\n"
            b += f"**Responsibility.** {sysrec['responsibility'].strip()}\n\n**Side.** {sysrec['side']}\n\n"
            b += f"**Threads.** {self._render_ref(sysrec['threads'].strip())}\n\n"
            if sysrec.get("persistence"):
                b += f"**Persistence.** {self._render_ref(sysrec['persistence'].strip())}\n\n"
            for key, title in (("extension_points", "Extension points"), ("interactions", "Interactions to expect"),
                               ("evidence", "Evidence"), ("questions", "Open questions")):
                if sysrec.get(key):
                    b += f"## {title}\n\n" + "\n".join(f"- {self._render_ref(i)}" for i in sysrec[key]) + "\n\n"
            self.put(f"_authored/systems/{slug(sysrec['id'])}.md", b, generated=False)

        classes = self.surface["classes"]
        for pkg in sorted(set(depth4) | set(authored)):
            d = depth4.get(pkg, {"classes": 0, "top_level": 0, "differs": 0, "subpackages": set()})
            types = by_pkg.get(pkg, [])
            b = fm(type="system", package=pkg) + f"# {pkg}\n\n"
            if pkg in authored:
                b += f"Analyst note: {link('_authored/systems/' + slug(pkg), authored[pkg]['title'])}\n\n"
            b += (f"{d['classes']} classes ({d['top_level']} top-level) across {len(d['subpackages'])} packages in the "
                  f"processed jar; {d['differs']} changed by Loom processing; {len(types)} hooked by Fabric API.\n\n")
            if types:
                b += "## Hooked types\n\n"
                for t in sorted(types):
                    rel = collections.Counter(e["relation"] for e in hooked[t])
                    mods = sorted({e.get("module") for e in hooked[t] if e.get("module")})
                    b += f"- {self.type_link(t)} -- " + ", ".join(f"{k}:{v}" for k, v in sorted(rel.items())) + f" -- by {', '.join(mods)}\n"
                b += "\n"
            b += "## Declared inventory\n\n"
            for sub in sorted(d["subpackages"]):
                names = sorted(k for k in classes if full_pkg(k) == sub and "$" not in k)
                if not names:
                    continue
                b += f"### `{sub}` ({len(names)} top-level)\n\n"
                b += ", ".join(self.type_link(n, short(n)) if f"40-Interfaces/{slug(n.replace('/', '.'))}" in self.note_index
                               else f"`{short(n)}`" for n in names) + "\n\n"
            self.put(f"20-Systems/{slug(pkg)}.md", b)

    # -- 30 mechanisms -----------------------------------------------------------
    def mechanisms(self) -> None:
        body = fm(type="index") + "# Modification mechanisms\n\n"
        body += ("Four families, kept apart because they compose differently:\n\n"
                 "1. **Data packs / resource packs** -- no code. See "
                 f"{link('00-Scope/Data_Driven_Surface', 'the data-driven surface')}.\n"
                 f"2. **Registries** -- code registers new content. See {link('30-Mechanisms/Registries')}.\n"
                 "3. **Fabric API modules** -- events, hooks and helpers, each implemented by "
                 "mixins into vanilla. Listed below with what each actually hooks.\n"
                 "4. **Direct mixins by a mod** -- the same mechanism Fabric API uses, applied by "
                 f"a mod itself. See {link('30-Mechanisms/Mixin')} and {link('30-Mechanisms/Transformation_Tests', 'the transformation tests')}.\n\n")
        body += "| module | lifecycle | env | mixins | injections | by injector | events published | api classes |\n|---|---|---|---|---|---|---|---|\n"
        by_mod: dict[str, list[dict]] = collections.defaultdict(list)
        for e in self.edges["edges"]:
            if e.get("module"):
                by_mod[e["module"]].append(e)
        for m in sorted(self.fabric["modules"], key=lambda m: m["id"]):
            lifecycle = ((m["declared"].get("custom") or {}).get("fabric-api:module-lifecycle", "?"))
            env = m["declared"].get("environment") or "*"
            es = by_mod.get(m["id"], [])
            inj = [e for e in es if e["relation"] in ("injects_into", "replaces", "wraps")]
            kinds = collections.Counter(e["injector"] for e in inj)
            pub = len({e["to"]["id"] for e in es if e["relation"] == "publishes_event"})
            body += (f"| {link('30-Mechanisms/' + slug(m['id']), m['id'])} | {lifecycle} | {env} | "
                     f"{m['counts']['mixin_classes_found']} | {len(inj)} | {', '.join(f'{k} {v}' for k, v in kinds.most_common())} | {pub} | {m['counts']['api_classes']} |\n")
        self.put("30-Mechanisms/_index.md", body)

        for m in self.fabric["modules"]:
            es = by_mod.get(m["id"], [])
            b = fm(type="mechanism", module=m["id"], version=m["version"], sha256=m["sha256"],
                   lifecycle=(m["declared"].get("custom") or {}).get("fabric-api:module-lifecycle", "?"))
            b += f"# {m['id']}\n\n"
            d = m["declared"]
            b += f"**Version** `{m['version']}` -- **artifact sha256** `{m['sha256']}`\n\n"
            b += "## Declared (fabric.mod.json)\n\n"
            b += f"- environment: `{d.get('environment') or '*'}`\n"
            b += f"- depends: `{json.dumps(d.get('depends'))}`\n"
            if d.get("breaks"):
                b += f"- breaks: `{json.dumps(d.get('breaks'))}`\n"
            b += f"- entrypoints: `{json.dumps(d.get('entrypoints'))}`\n"
            b += f"- mixin configs: `{json.dumps(d.get('mixins'))}`\n"
            if d.get("accessWidener"):
                b += f"- access widener: `{d['accessWidener']}`\n"
            b += (f"- mixin classes: {m['counts']['mixin_classes_found']} found by annotation, "
                  f"{m['counts']['mixin_classes_declared']} declared in configs; extraction failures: {m['counts']['extraction_failures']}\n")
            b += "\n## Events this module publishes\n\n"
            module_events = sorted({e["to"]["id"] for e in es if e["relation"] == "publishes_event"} |
                                   {e["to"]["id"] for e in es if e["relation"] == "callback_of"})
            if module_events:
                for ev in module_events:
                    b += f"- {link('50-Interactions/events/' + slug(ev), ev.split('.')[-2] + '.' + ev.split('.')[-1])}\n"
            else:
                b += "- none found by extraction\n"
            b += ("\n## Vanilla methods this module modifies\n\nOne row per (injection, selector). `resolution` says how "
                  "the selector matched the processed jar; `points` are the @At targets with their own resolution.\n\n"
                  "| vanilla method | descriptor | resolution | injector | points | env | priority | handler |\n|---|---|---|---|---|---|---|---|\n")
            for e in sorted((e for e in es if e["relation"] in ("injects_into", "replaces", "wraps")),
                            key=lambda e: (e["to"]["owner"], e["to"]["id"])):
                pts = "; ".join(f"{p['value']}" + (f" `{p.get('target')}`" if p.get("target") else "")
                                + (f" ({p['resolution']['state']})" if p.get("resolution") else "") for p in e.get("points", []))
                b += (f"| {self.type_link(e['to']['owner'])}.`{e['to']['id']}` | `{e['to'].get('descriptor') or '?'}` | "
                      f"{e['to']['resolution']['state']} | @{e['injector']} | {pts or '-'} | {e['applies_to'].get('environment')} | "
                      f"{e.get('priority')}{'' if e.get('priority_source') == 'annotation' else ' (default)'} | "
                      f"`{short(e['from']['owner'])}.{e['from']['id']}` |\n")
            b += "\n## API surface\n\n"
            for api in sorted(m["api"], key=lambda a: a["fqcn"]):
                b += f"- {link('40-Interfaces/' + slug(api['fqcn']), api['fqcn'].split('.')[-1])} ({api['kind']}, {len(api['members'])} members)\n"
